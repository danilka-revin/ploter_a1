export function PortHelp() {
  return (
    <div className="port-guide">
      <ol className="guide-steps">
        <li>
          <b>Проще всего:</b> нажмите «Найти батарею». Программа по очереди опросит все порты и покажет,
          на каком из них отвечает BMS. Если батарея одна, она подключится сама.
        </li>
        <li>
          <b>Вынуть и вставить:</b> отключите USB–UART адаптер, который идёт к плате батареи. Нажмите «Обновить список».
          Затем вставьте адаптер обратно. Порт, который появился, и есть порт батареи.
        </li>
        <li>
          <b>Windows:</b> Диспетчер устройств → «Порты (COM и LPT)». В скобках написан номер, например
          «USB-SERIAL CH340 (COM4)». Жёлтый значок — драйвер не установлен.
        </li>
        <li>
          <b>Ubuntu:</b> в терминале выполните <code>ls /dev/ttyUSB* /dev/ttyACM*</code> до и после подключения адаптера.
          Или сразу после вставки: <code>dmesg | tail -5</code> — строка «attached to ttyUSB0» покажет порт.
        </li>
        <li>
          <b>Проверка:</b> если после подключения напряжение и число ячеек совпадают с батареей (например, 12 ячеек
          и около 38 В для 12S), порт выбран верно.
        </li>
      </ol>
      <div className="guide-trouble">
        <b>Если порт не открывается:</b> закройте JBDTools и другие программы, которые могут его занимать;
        в Ubuntu добавьте себя в группу <code>dialout</code> и войдите в систему заново.
        <br />
        <b>Если порт открылся, а плата молчит:</b> поменяйте местами RX и TX, проверьте GND и питание батареи.
      </div>
      <p className="muted small">
        Полная инструкция с командами: <code>jbd-bms-app/docs/kak-najti-port.md</code>.
      </p>
    </div>
  );
}
